create or replace function private.battle_in_character_recent_50(p_character_id uuid,p_kind text,p_battle_id uuid)
returns boolean language sql stable security definer set search_path to 'pg_catalog','public','private'
as $function$
  select exists(
    select 1 from (
      select recent.kind,recent.battle_id from (
        select 'solo'::text kind,dr.id battle_id,coalesce(dr.ended_at,dr.started_at) sort_at
        from public.dungeon_runs dr where dr.character_id=p_character_id and dr.status<>'active'
        union all
        select 'party'::text,pdr.id,coalesce(pdr.ended_at,pdr.started_at)
        from public.party_dungeon_runs pdr join public.party_dungeon_run_members prm on prm.run_id=pdr.id
        where prm.character_id=p_character_id and pdr.status<>'active'
        union all
        select 'pvp'::text,pd.id,coalesce(pd.ended_at,pd.started_at,pd.created_at)
        from public.pvp_duels pd
        where p_character_id in(pd.challenger_character_id,pd.opponent_character_id) and pd.status not in('pending','active')
      ) recent order by recent.sort_at desc,recent.battle_id desc limit 50
    ) kept where kept.kind=p_kind and kept.battle_id=p_battle_id
  );
$function$;

create or replace function private.prune_battle_history(p_character_id uuid)
returns void language plpgsql security definer set search_path to 'pg_catalog','public','private'
as $function$
declare v_id uuid;
begin
  if p_character_id is null then return; end if;
  for v_id in
    select dr.id from public.dungeon_runs dr
    where dr.character_id=p_character_id and dr.status<>'active'
      and not private.battle_in_character_recent_50(p_character_id,'solo',dr.id)
  loop
    delete from private.battle_consumable_usages where battle_kind='solo' and battle_id=v_id;
    delete from private.battle_reward_snapshots where battle_kind='solo' and battle_id=v_id;
    delete from private.battle_equipment_snapshots where battle_kind='solo' and battle_id=v_id;
    delete from public.dungeon_runs where id=v_id;
  end loop;

  for v_id in
    select pdr.id
    from public.party_dungeon_runs pdr
    join public.party_dungeon_run_members mine on mine.run_id=pdr.id
    where mine.character_id=p_character_id and pdr.status<>'active'
      and not private.battle_in_character_recent_50(p_character_id,'party',pdr.id)
      and not exists(
        select 1 from public.party_dungeon_run_members member
        where member.run_id=pdr.id and private.battle_in_character_recent_50(member.character_id,'party',pdr.id)
      )
  loop
    delete from private.battle_consumable_usages where battle_kind='party' and battle_id=v_id;
    delete from private.battle_reward_snapshots where battle_kind='party' and battle_id=v_id;
    delete from private.battle_equipment_snapshots where battle_kind='party' and battle_id=v_id;
    delete from public.party_dungeon_runs where id=v_id;
  end loop;

  for v_id in
    select pd.id from public.pvp_duels pd
    where p_character_id in(pd.challenger_character_id,pd.opponent_character_id)
      and pd.status not in('pending','active')
      and not private.battle_in_character_recent_50(p_character_id,'pvp',pd.id)
      and not private.battle_in_character_recent_50(pd.challenger_character_id,'pvp',pd.id)
      and not private.battle_in_character_recent_50(pd.opponent_character_id,'pvp',pd.id)
  loop
    delete from private.battle_consumable_usages where battle_kind='pvp' and battle_id=v_id;
    delete from private.battle_reward_snapshots where battle_kind='pvp' and battle_id=v_id;
    delete from private.battle_equipment_snapshots where battle_kind='pvp' and battle_id=v_id;
    delete from public.pvp_duels where id=v_id;
  end loop;
end;
$function$;

create or replace function private.prune_battle_history_after_finish()
returns trigger language plpgsql security definer set search_path to 'pg_catalog','public','private'
as $function$
declare v_member record;
begin
  if tg_table_name='dungeon_runs' then
    if new.status<>'active' and old.status is distinct from new.status then perform private.prune_battle_history(new.character_id); end if;
  elsif tg_table_name='party_dungeon_runs' then
    if new.status<>'active' and old.status is distinct from new.status then
      for v_member in select character_id from public.party_dungeon_run_members where run_id=new.id loop
        perform private.prune_battle_history(v_member.character_id);
      end loop;
    end if;
  elsif tg_table_name='pvp_duels' then
    if new.status not in('pending','active') and old.status is distinct from new.status then
      perform private.prune_battle_history(new.challenger_character_id);
      if new.opponent_character_id is distinct from new.challenger_character_id then perform private.prune_battle_history(new.opponent_character_id); end if;
    end if;
  end if;
  return new;
end;
$function$;

drop trigger if exists prune_finished_solo_battle_history on public.dungeon_runs;
create trigger prune_finished_solo_battle_history after update of status on public.dungeon_runs
for each row execute function private.prune_battle_history_after_finish();
