create trigger prune_finished_party_battle_history after update of status on public.party_dungeon_runs
for each row execute function private.prune_battle_history_after_finish();
drop trigger if exists prune_finished_pvp_battle_history on public.pvp_duels;
create trigger prune_finished_pvp_battle_history after update of status on public.pvp_duels
for each row execute function private.prune_battle_history_after_finish();

create or replace function public.get_battle_history_economy(p_character_id uuid,p_kind text,p_battle_id uuid)
returns jsonb language plpgsql security definer set search_path to 'pg_catalog','public','private'
as $function$
declare
  caller uuid:=auth.uid(); v_started_at timestamptz; v_tracking_started_at timestamptz;
  v_reward private.battle_reward_snapshots; v_reward_tracked boolean:=false;
  v_gold integer; v_experience integer; v_loot jsonb:='[]'::jsonb; v_consumables jsonb:='[]'::jsonb;
begin
  if caller is null then raise exception 'AUTH_REQUIRED'; end if;
  if not exists(select 1 from public.characters c where c.id=p_character_id and c.owner_user_id=caller) then raise exception 'CHARACTER_NOT_OWNED'; end if;
  select consumables_started_at into v_tracking_started_at from private.battle_history_tracking_config where singleton=true;
  select * into v_reward from private.battle_reward_snapshots r
  where r.battle_kind=p_kind and r.battle_id=p_battle_id and r.character_id=p_character_id;

  if p_kind='solo' then
    if not exists(select 1 from public.dungeon_runs dr where dr.id=p_battle_id and dr.character_id=p_character_id) then raise exception 'BATTLE_NOT_FOUND'; end if;
    select dr.started_at,
      case when v_reward.battle_id is not null then v_reward.gold when dr.status='completed' then coalesce(dr.reward_gold,0) else 0 end,
      case when v_reward.battle_id is not null then v_reward.experience when dr.status='completed' then coalesce(dr.reward_experience,0) else 0 end
    into v_started_at,v_gold,v_experience from public.dungeon_runs dr where dr.id=p_battle_id;
    v_reward_tracked:=true;
    select coalesce(jsonb_agg(jsonb_build_object(
      'item_definition_id',x.item_definition_id,'name',x.name,'slug',x.slug,'rarity',x.rarity,'quantity',x.quantity,'source_type',x.source_type
    ) order by x.name),'[]'::jsonb) into v_loot
    from (
      select d.id item_definition_id,d.name,d.slug,d.rarity,sum(ld.quantity)::integer quantity,min(ld.source_type) source_type
      from public.loot_drops ld join public.item_definitions d on d.id=ld.item_definition_id
      where ld.dungeon_run_id=p_battle_id and ld.character_id=p_character_id
      group by d.id,d.name,d.slug,d.rarity
    ) x;
    if v_reward.battle_id is not null and jsonb_typeof(v_reward.items)='array' then v_loot:=coalesce(v_loot,'[]'::jsonb)||v_reward.items; end if;

  elsif p_kind='party' then
    if not exists(select 1 from public.party_dungeon_run_members prm where prm.run_id=p_battle_id and prm.character_id=p_character_id) then raise exception 'BATTLE_NOT_FOUND'; end if;
    select pdr.started_at into v_started_at from public.party_dungeon_runs pdr where pdr.id=p_battle_id;
    if v_reward.battle_id is not null then v_reward_tracked:=true; v_gold:=v_reward.gold; v_experience:=v_reward.experience;
    elsif exists(select 1 from public.party_dungeon_runs pdr where pdr.id=p_battle_id and pdr.status<>'completed') then
      v_reward_tracked:=true; v_gold:=0; v_experience:=0;
    else v_reward_tracked:=false; v_gold:=null; v_experience:=null; end if;
    select coalesce(jsonb_agg(jsonb_build_object(
      'item_definition_id',x.item_definition_id,'name',x.name,'slug',x.slug,'rarity',x.rarity,'quantity',x.quantity,'source_type',x.source_type
    ) order by x.name),'[]'::jsonb) into v_loot
    from (
      select d.id item_definition_id,d.name,d.slug,d.rarity,sum(ld.quantity)::integer quantity,min(ld.source_type) source_type
      from public.party_loot_drops ld join public.item_definitions d on d.id=ld.item_definition_id
      where ld.run_id=p_battle_id and ld.character_id=p_character_id
      group by d.id,d.name,d.slug,d.rarity
    ) x;
    if v_reward.battle_id is not null and jsonb_typeof(v_reward.items)='array' then v_loot:=coalesce(v_loot,'[]'::jsonb)||v_reward.items; end if;

  elsif p_kind='pvp' then
    if not exists(select 1 from public.pvp_duels pd where pd.id=p_battle_id and p_character_id in(pd.challenger_character_id,pd.opponent_character_id)) then raise exception 'BATTLE_NOT_FOUND'; end if;
    select coalesce(pd.started_at,pd.created_at) into v_started_at from public.pvp_duels pd where pd.id=p_battle_id;
    v_reward_tracked:=true; v_gold:=0; v_experience:=0; v_loot:='[]'::jsonb;
  else raise exception 'INVALID_BATTLE_KIND'; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'item_definition_id',x.item_definition_id,'name',x.item_name,'slug',x.item_slug,'quantity',x.quantity,'usage_kind',x.usage_kind
  ) order by x.item_name),'[]'::jsonb) into v_consumables
  from (
    select min(u.item_definition_id::text)::uuid item_definition_id,u.item_name,u.item_slug,u.usage_kind,sum(u.quantity)::integer quantity
    from private.battle_consumable_usages u
    where u.battle_kind=p_kind and u.battle_id=p_battle_id and u.character_id=p_character_id
    group by u.item_name,u.item_slug,u.usage_kind
  ) x;

  return jsonb_build_object(
    'reward',jsonb_build_object('tracked',v_reward_tracked,'gold',v_gold,'experience',v_experience,'loot',coalesce(v_loot,'[]'::jsonb)),
    'consumables',coalesce(v_consumables,'[]'::jsonb),
    'consumables_complete',coalesce(v_started_at>=v_tracking_started_at,false)
  );
end;
$function$;

