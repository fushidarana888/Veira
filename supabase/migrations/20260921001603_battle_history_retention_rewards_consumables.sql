create or replace function private.log_active_battle_consumable(p_character_id uuid,p_item_definition_id uuid,p_quantity integer,p_usage_kind text default 'consumable')
returns void language plpgsql security definer set search_path to 'pg_catalog','public','private'
as $function$
declare v_kind text; v_battle_id uuid; v_item public.item_definitions;
begin
  if p_character_id is null or p_item_definition_id is null or coalesce(p_quantity,0)<=0 then return; end if;
  select dr.id into v_battle_id from public.dungeon_runs dr where dr.character_id=p_character_id and dr.status='active' order by dr.started_at desc limit 1;
  if v_battle_id is not null then v_kind:='solo';
  else
    select pdr.id into v_battle_id from public.party_dungeon_runs pdr join public.party_dungeon_run_members prm on prm.run_id=pdr.id
    where prm.character_id=p_character_id and pdr.status='active' order by pdr.started_at desc limit 1;
    if v_battle_id is not null then v_kind:='party';
    else
      select pd.id into v_battle_id from public.pvp_duels pd
      where pd.status='active' and p_character_id in(pd.challenger_character_id,pd.opponent_character_id)
      order by coalesce(pd.started_at,pd.created_at) desc limit 1;
      if v_battle_id is not null then v_kind:='pvp'; end if;
    end if;
  end if;
  if v_battle_id is null or v_kind is null then return; end if;
  select * into v_item from public.item_definitions where id=p_item_definition_id;
  if v_item.id is null then return; end if;
  insert into private.battle_consumable_usages(battle_kind,battle_id,character_id,item_definition_id,item_name,item_slug,quantity,usage_kind)
  values(v_kind,v_battle_id,p_character_id,v_item.id,v_item.name,v_item.slug,p_quantity,coalesce(nullif(p_usage_kind,''),'consumable'));
end;
$function$;

create or replace function private.record_battle_reward(p_battle_kind text,p_battle_id uuid,p_character_id uuid,p_gold integer,p_experience integer,p_items jsonb default '[]'::jsonb)
returns void language plpgsql security definer set search_path to 'pg_catalog','public','private'
as $function$
begin
  if p_battle_kind not in ('solo','party','pvp') or p_battle_id is null or p_character_id is null then return; end if;
  insert into private.battle_reward_snapshots(battle_kind,battle_id,character_id,gold,experience,items,recorded_at)
  values(p_battle_kind,p_battle_id,p_character_id,greatest(0,coalesce(p_gold,0)),greatest(0,coalesce(p_experience,0)),coalesce(p_items,'[]'::jsonb),now())
  on conflict(battle_kind,battle_id,character_id) do update
  set gold=excluded.gold,experience=excluded.experience,items=excluded.items,recorded_at=excluded.recorded_at;
end;
$function$;

create or replace function private.event_reward_item_snapshot(p_reward jsonb)
