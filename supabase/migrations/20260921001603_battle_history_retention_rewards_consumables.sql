from public.combat_turns t
join public.combat_encounters ce on ce.id=t.encounter_id
join public.item_definitions d on d.slug=substring(t.action_type from 6)
where ce.dungeon_run_id is not null and t.actor='player' and t.action_type like 'item_%';

insert into private.battle_consumable_usages(battle_kind,battle_id,character_id,item_definition_id,item_name,item_slug,quantity,usage_kind,used_at)
select 'solo',ce.dungeon_run_id,ce.character_id,d.id,d.name,d.slug,1,'combat_scroll',t.created_at
from public.combat_turns t
join public.combat_encounters ce on ce.id=t.encounter_id
join public.spell_definitions s on s.slug=substring(t.action_type from 8)
join lateral (
  select id,name,slug from public.item_definitions x
  where x.scroll_mode='cast' and x.scroll_spell_id=s.id
  order by x.required_level,x.name limit 1
) d on true
where ce.dungeon_run_id is not null and t.actor='player' and t.action_type like 'scroll_%';

insert into private.battle_consumable_usages(battle_kind,battle_id,character_id,item_definition_id,item_name,item_slug,quantity,usage_kind,used_at)
select 'party',ce.run_id,t.actor_character_id,d.id,d.name,d.slug,1,'combat_scroll',t.created_at
from public.party_combat_turns t
join public.party_combat_encounters ce on ce.id=t.encounter_id
join public.item_definitions d on d.slug='combat_scroll_last_sacrifice'
where t.actor_type='player' and t.actor_character_id is not null and t.action_type='scroll_last_sacrifice';

